func wordOfTheDay(_ now: Date = Date()) -> DayWord {
    let midnight = Calendar.current.startOfDay(for: now)
    let dayNumber = Int(floor(midnight.timeIntervalSince1970 / 86_400))
    let count = dayWords.count
    return dayWords[((dayNumber % count) + count) % count]
}
